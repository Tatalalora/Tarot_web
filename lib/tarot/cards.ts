function buildCards(): TarotCardData[] {
  const majors: TarotCardData[] = MAJOR_SEEDS.map(
    ([name, nameEn, keywords, upright, reversed], i) => {
      const n = String(i).padStart(2, "0");
      return {
        id: `major-${n}`,
        name,
        nameEn,
        arcana: "major",
        number: i,
        keywords,
        upright,
        reversed,
        image: `/cards/major-${n}.jpg`,
      };
    },
  );

  const minors: TarotCardData[] = [];
  (Object.keys(SUITS) as Suit[]).forEach((suit) => {
    const info = SUITS[suit];
    for (let rank = 1; rank <= 14; rank++) {
      const n = String(rank).padStart(2, "0");
      const idx = rank - 1;
      minors.push({
        id: `${suit}-${n}`,
        name: `${info.name}${RANK_NAMES[idx]}`,
        nameEn: `${RANK_NAMES_EN[idx]} of ${info.element}`,
        arcana: "minor",
        suit,
        number: rank,
        keywords: info.keywords[idx],
        upright: info.upright[idx],
        reversed: info.reversed[idx],
        image: `/cards/${suit}-${n}.jpg`,
      });
    }
  });

  return [...majors, ...minors];
}

export const TAROT_CARDS: TarotCardData[] = buildCards();

